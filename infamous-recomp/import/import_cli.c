/* import_cli: test and maintainer tool for disc_import.c (macOS).
 *
 *   import_cli probe  <iso|folder> [--dkey FILE]
 *   import_cli import <iso|folder> <dest_root> [--dkey FILE]
 *   import_cli self   <EBOOT.BIN> <out.elf> [--meta-key HEX --meta-iv HEX]
 *   import_cli make-key <EBOOT.BIN> --erk HEX --riv HEX   > import/eboot_key.h
 *
 * make-key needs the PS3 APP key for the SELF's key revision (RPCS3's key
 * vault lists them). It prints only this file's metadata key and IV, which
 * is all the app needs; the APP key itself never goes into the build.
 *
 * Build: clang -O2 -o import_cli import_cli.c disc_import.c -lz -framework CoreFoundation */
#include "disc_import.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

static int hex_bytes(const char* s, uint8_t* out, size_t n)
{
    if (!s || strlen(s) != 2 * n) return -1;
    for (size_t i = 0; i < n; i++) {
        char t[3] = { s[2 * i], s[2 * i + 1], 0 };
        char* e;
        out[i] = (uint8_t)strtoul(t, &e, 16);
        if (*e) return -1;
    }
    return 0;
}

static const char* opt(int argc, char** argv, const char* name)
{
    for (int i = 1; i + 1 < argc; i++)
        if (!strcmp(argv[i], name)) return argv[i + 1];
    return NULL;
}

static void progress(void* ctx, double f, const char* what)
{
    (void)ctx;
    fprintf(stderr, "\r%5.1f%%  %-60.60s", f * 100, what);
    if (f >= 1.0) fputc('\n', stderr);
}

int main(int argc, char** argv)
{
    char err[1024] = "";
    if (argc < 3) {
        fprintf(stderr, "usage: see the top of import_cli.c\n");
        return 2;
    }
    const char* cmd = argv[1];
    if (!strcmp(cmd, "probe")) {
        di_info in;
        const di_status s = di_probe(argv[2], opt(argc, argv, "--dkey"), &in, err, sizeof err);
        printf("status:    %s\n", di_status_name(s));
        if (err[0]) printf("message:   %s\n", err);
        printf("kind:      %s%s\n", in.is_iso ? "disc image" : "folder", in.encrypted ? " (encrypted)" : "");
        printf("title:     %s (%s) version %s\n", in.title, in.title_id, in.version);
        printf("bytes:     %.2f GB\n", in.bytes / 1e9);
        printf("eboot key: %s\n", di_have_eboot_key() ? "built in" : "none");
        return s == DI_OK ? 0 : 1;
    }
    if (!strcmp(cmd, "import") && argc >= 4) {
        di_callbacks cb = { progress, NULL, NULL };
        const di_status s = di_import(argv[2], opt(argc, argv, "--dkey"), argv[3], &cb, err, sizeof err);
        printf("status: %s%s%s\n", di_status_name(s), err[0] ? " -- " : "", err);
        return s == DI_OK ? 0 : 1;
    }
    if (!strcmp(cmd, "self") && argc >= 4) {
        uint8_t k[16], iv[16];
        const char* ks = opt(argc, argv, "--meta-key");
        const char* is = opt(argc, argv, "--meta-iv");
        const int given = ks && is;
        if (given && (hex_bytes(ks, k, 16) || hex_bytes(is, iv, 16))) { fprintf(stderr, "bad --meta-key/--meta-iv\n"); return 2; }
        const di_status s = di_self_to_elf(argv[2], argv[3], given ? k : NULL, given ? iv : NULL, err, sizeof err);
        char hex[65] = "";
        if (s == DI_OK) di_sha256_file(argv[3], hex);
        printf("status: %s%s%s\nsha256: %s\n", di_status_name(s), err[0] ? " -- " : "", err, hex);
        return s == DI_OK ? 0 : 1;
    }
    if (!strcmp(cmd, "make-key")) {
        uint8_t erk[32], riv[16], k[16], iv[16];
        if (hex_bytes(opt(argc, argv, "--erk"), erk, 32) || hex_bytes(opt(argc, argv, "--riv"), riv, 16)) {
            fprintf(stderr, "make-key needs --erk (64 hex digits) and --riv (32 hex digits)\n");
            return 2;
        }
        di_status s = di_self_meta_key(argv[2], erk, riv, k, iv, err, sizeof err);
        if (s != DI_OK) { fprintf(stderr, "%s\n", err); return 1; }
        /* Prove it: decrypt with the result and check the ELF. */
        char tmpl[] = "/tmp/import_cli_XXXXXX";
        const int fd = mkstemp(tmpl);
        if (fd >= 0) close(fd);
        s = di_self_to_elf(argv[2], tmpl, k, iv, err, sizeof err);
        char hex[65] = "";
        if (s == DI_OK) di_sha256_file(tmpl, hex);
        unlink(tmpl);
        if (s != DI_OK) { fprintf(stderr, "decrypt with the new key failed: %s\n", err); return 1; }
        fprintf(stderr, "EBOOT.elf sha256 %s\n", hex);
        printf("/* Generated by import_cli make-key. Not in git: this is a key for one\n"
               " * game file. The metadata key and IV of EBOOT.BIN (BCES00220), which\n"
               " * the app uses to decrypt it on the player's device. */\n#pragma once\n");
        printf("static const unsigned char k_eboot_meta_key[16] = {");
        for (int i = 0; i < 16; i++) printf("%s0x%02x", i ? ", " : " ", k[i]);
        printf(" };\nstatic const unsigned char k_eboot_meta_iv[16] = {");
        for (int i = 0; i < 16; i++) printf("%s0x%02x", i ? ", " : " ", iv[i]);
        printf(" };\n");
        return 0;
    }
    fprintf(stderr, "unknown command\n");
    return 2;
}
